#!/usr/bin/env node
// Writes .dev.vars with a fresh random token for each role, for `npm run dev` and the tests.
//
//   node scripts/gen-dev-vars.mjs [--force] [--out <path>]
//
// --force  replace an existing file (every role gets a new token)
// --out    write somewhere other than <repo>/.dev.vars
import { randomBytes } from "node:crypto";
import { chmodSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const ROLES = [
  ["orchestrator", "ORCHESTRATOR_TOKEN"],
  ["creative-director", "CREATIVE_DIRECTOR_TOKEN"],
  ["developer", "DEVELOPER_TOKEN"],
  ["human", "HUMAN_TOKEN"],
];
const LOCAL_URL = "http://127.0.0.1:8787";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

let args;
try {
  args = parseArgs({
    options: { force: { type: "boolean", default: false }, out: { type: "string" } },
  }).values;
} catch (error) {
  console.error(`${error.message}\nUsage: node scripts/gen-dev-vars.mjs [--force] [--out <path>]`);
  process.exit(2);
}
const out = resolve(args.out ?? resolve(repoRoot, ".dev.vars"));

// 36 random bytes encode to exactly 48 base64url characters.
const tokens = ROLES.map(([role, name]) => ({ role, name, token: randomBytes(36).toString("base64url") }));
const content = [
  "# Local role tokens for `npm run dev` and the tests. Generated by scripts/gen-dev-vars.mjs. Never commit.",
  ...tokens.map(({ name, token }) => `${name}=${token}`),
  "",
].join("\n");

try {
  writeFileSync(out, content, { flag: args.force ? "w" : "wx", mode: 0o600 });
} catch (error) {
  if (error.code !== "EEXIST") throw error;
  console.error(`${out} already exists. Re-run with --force to replace it (every role gets a new token).`);
  process.exit(1);
}
chmodSync(out, 0o600);

console.log(`Wrote ${out} with ${tokens.length} role tokens.\n`);
console.log(`MCP URLs for \`npm run dev\` (${LOCAL_URL}):`);
for (const { role, token } of tokens) console.log(`  ${role.padEnd(18)} ${LOCAL_URL}/mcp/${token}`);
console.log(`\nLedger page: ${LOCAL_URL}/ (sign in with HUMAN_TOKEN).`);
